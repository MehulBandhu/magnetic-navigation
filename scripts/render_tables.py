    for k, v in em["summary"].items():
        out.append(f"| {k} | {v['tiles']} | {v['beta_median']:.2f} ({v['beta_q10']:.2f}, {v['beta_q90']:.2f}) | {v['frac_beta_in_2p5_4']:.2f} | {v.get('frac_beta_clipped', float('nan')):.2f} | {v['mse_network_median']:.2f} | {v['mse_wiener_median']:.2f} | {v.get('mse_wiener_beta35_median', float('nan')):.2f} | {v.get('mse_wiener_beta35_stationary_median', float('nan')):.2f} | {v['floor_predicted_median']:.2f} | {v['mse_interp_median']:.2f} | {v['wiener_over_own_floor_median']:.2f} | {v.get('network_over_wiener_beta35_median', float('nan')):.2f} | {v.get('network_over_wiener_beta35_stationary_median', float('nan')):.2f} | {v['frac_network_beats_interp']:.2f} | {v.get('nonlinearity_median', float('nan')):.3f} |")
