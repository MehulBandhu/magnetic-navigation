"""Write docs/results_tables.md from the committed jsons, so that every number quoted in the
write-up comes from one place. Run after `make fit` (make tables does both)."""
import glob
import json
import os
import sys
from collections import defaultdict

out = ["# Results tables\n", "Generated by `python scripts/render_tables.py` from `results/` and `runs/`. Do not edit by hand.\n"]

# ---- scaling grid
fits = json.load(open("results/fit.json")) if os.path.exists("results/fit.json") else []
if fits:
    out += ["\n## Parameter slopes of the excess over the floor (fixed-budget protocol)\n",
            "| condition | floor nT^2 | alpha, all sizes | below knee | above knee | knee m/l | broken law: below / knee / above | LOO by size: broken / additive | runs still improving |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in fits:
        b = r.get("broken_power_law", {})
        out.append(f"| beta {r['beta']}, {r['h']:.0f} m | {r['floor']:.4f} | {r.get('alpha_global', float('nan')):.2f} +- {r.get('alpha_global_err', float('nan')):.2f} "
                   f"| {r.get('alpha_small', float('nan')):.2f} +- {r.get('alpha_small_err', float('nan')):.2f} | {r.get('alpha_large', float('nan')):.2f} +- {r.get('alpha_large_err', float('nan')):.2f} "
                   f"| {r.get('knee_m_over_l', float('nan')):.1f}x | {b.get('alpha_below', float('nan')):.1f} / {b.get('knee_N', float('nan'))/1e6:.2g}M / {b.get('alpha_above', float('nan')):.1f} "
                   f"| {b.get('loo', float('nan')):.1f} / {r.get('additive_loo_sizes', float('nan')):.1f} | {r['n_unconverged']} / {r['n_runs']} |")
    out += ["\nBands are the cell-level bootstrap described in docs/problem2.md (heuristic). The broken-law parameters and the "
            "leave-one-size-out errors come from a non-convex multi-start fit and move at the 10 to 25% level between scipy "
            "versions and optimiser paths; they are quoted to one decimal for that reason. The slopes, knee ratios, floors, "
            "local deltas and floor profiles are stable.\n",
            "\n## Local data slopes, per model size (minus dlog excess / dlog D)\n"]
    for r in fits:
        out.append(f"\n**beta {r['beta']}, {r['h']:.0f} m**\n")
        segs = sorted({(g['D_from'], g['D_to']) for s in r['delta_local'].values() for g in s})
        out.append("| size | " + " | ".join(f"{a}->{b}" for a, b in segs) + " |")
        out.append("|---|" + "---|" * len(segs))
        for sz, s in r["delta_local"].items():
            d = {(g["D_from"], g["D_to"]): g for g in s}
            out.append(f"| {sz} | " + " | ".join(f"{d[k]['delta']:.2f} +- {d[k].get('err', float('nan')):.2f}" if k in d else "" for k in segs) + " |")
    out.append("\nBands: cell-level bootstrap (seeds resampled where present, singleton cells perturbed by the median seed scatter).\n")
    out += ["\n## Is the floor identified? (loss = E + A N^-alpha + B D^-delta fitted and scored in log total loss at each candidate E; the minimum is the free-floor estimate)\n",
            "| condition | exact floor | best E | best E / exact | err at best | err at exact | E range within 5% of the minimum |", "|---|---|---|---|---|---|---|"]
    for r in fits:
        for key, label in [("floor_profile", "all sizes"), ("floor_profile_large", "l, xl, xxl only")]:
            pf = r.get(key)
            if pf:
                out.append(f"| beta {r['beta']}, {r['h']:.0f} m ({label}) | {r['floor']:.3f} | {pf['best_E']:.3f} | {pf.get('best_E_over_exact', pf['best_E'] / r['floor']):.2f} | {pf['best_err']:.3f} | {pf['err_at_exact']:.3f} | [{pf['range_within_5pct'][0]:.3f}, {pf['range_within_5pct'][1]:.3f}] |")
    out.append("\nAn earlier version of this profile fitted and scored log(loss - E), whose scale changes with E; that objective favoured E near zero and was withdrawn.")
    out += ["\n## Additive form with the floor fixed to the exact value (bands: cell-level bootstrap, heuristic)\n",
            "| condition | alpha | delta | LOO over cells |", "|---|---|---|---|"]
    for r in fits:
        fx = r.get("additive_fixed_floor", {})
        dl = (f"{fx.get('delta', float('nan')):.2f} +- {fx.get('delta_err', float('nan')):.2f}") if fx.get("delta_identified", True) else "unidentified (at the optimiser bound)"
        out.append(f"| beta {r['beta']}, {r['h']:.0f} m | {fx.get('alpha', float('nan')):.2f} +- {fx.get('alpha_err', float('nan')):.2f} | {dl} | {fx.get('loo', float('nan')):.2f} |")

# ---- compute-optimal from the curves
if os.path.exists("results/compute_optimal.json"):
    co = json.load(open("results/compute_optimal.json"))
    out += ["\n## Compute-optimal allocation from the logged curves (C = 6 N S T, S = examples seen)\n",
            "| condition | alpha (fit) | delta_S (fit) | N* ~ C^ (fit) | best N along the envelope ~ C^ | runs / points |", "|---|---|---|---|---|---|"]
    for k, v in co.items():
        flag = " (form does not describe these curves: alpha above 2)" if v['alpha'] > 2 else ""
        out.append(f"| beta {v['beta']}, {v['h']:.0f} m | {v['alpha']:.2f} | {v['delta_S']:.2f} | {v['N_exponent']:.2f}{flag} | {v.get('envelope_N_exponent', float('nan')):.2f} | {v['n_runs']} / {v['n_points']} |")
    out.append("\nThe fit uses the last two thirds of each run. The envelope column is the parameter count of the best run at each compute level regressed on compute; it is the same in every condition because C depends only on size and steps and the largest model reaching a compute level is always the best, so it reflects the grid's schedule, not the task. For both: points along one cosine schedule are not independent runs of that length; the long run at step 8000 (0.876) beat the run whose schedule ended at 8000 (1.104), a 21% effect.\n")
    out += ["\n## Parameter slope at equal steps (the budget of the grid grows with size: 4k to 14k steps, lr 2e-3 to 4e-4)\n",
            "| condition | slope at 4000 steps, all sizes | slope at 8000 steps, l to xxl | grid slope (size-dependent budget) |", "|---|---|---|---|"]
    fit_by = {f"{f['beta']}_{f['h']:.0f}": f for f in fits}
    for k, v in co.items():
        g = fit_by.get(k, {})
        e4 = v.get("alpha_equal_steps_4000"); e8 = v.get("alpha_equal_steps_8000_large")
        out.append(f"| beta {v['beta']}, {v['h']:.0f} m | {e4 if e4 is not None else float('nan'):.2f} | {e8 if e8 is not None else float('nan'):.2f} | {g.get('alpha_global', float('nan')):.2f} |")
    out.append("\nRead from the logged curves at the same step for every size, so the step-count part of the size-dependent budget is removed; the learning rate still differs by size.")
    out.append("\nCaveat: points along one cosine schedule are not independent runs of that length; the long run at step 8000 (0.876) beat the run whose schedule ended at 8000 (1.104), a 21% effect.\n")

